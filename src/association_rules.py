"""
Layer 4D — Association Rule Generation and Evaluation
Project: Comparative Frequent Pattern Mining and Customer Behaviour Analytics

Input:
    experiments/results/apriori_itemsets.csv
    Generated by src/apriori.py

Outputs:
    experiments/results/association_rules.csv
    experiments/results/association_rules_summary.json

Rules are generated from frequent itemsets. For each rule A -> B:
    support(A -> B) = support(A union B)
    confidence(A -> B) = support(A union B) / support(A)
    lift(A -> B) = confidence(A -> B) / support(B)

Run from project root:
    python src/association_rules.py
    python src/association_rules.py --min-confidence 0.5 --min-lift 1.0
"""

from __future__ import annotations

import argparse
import json
from datetime import datetime, timezone
from itertools import combinations
from pathlib import Path

import pandas as pd

PROJECT_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_INPUT = PROJECT_ROOT / "experiments" / "results" / "apriori_itemsets.csv"
DEFAULT_OUTPUT_DIR = PROJECT_ROOT / "experiments" / "results"


def load_itemsets(path: Path) -> tuple[dict[frozenset[str], dict], dict[str, float]]:
    if not path.is_file():
        raise FileNotFoundError(
            f"Frequent-itemset file not found: {path}\n"
            "Run `python src/apriori.py` first."
        )

    frame = pd.read_csv(path)
    required = {"itemset", "length", "support_count", "support"}
    if not required.issubset(frame.columns):
        raise ValueError(f"Input must contain columns: {sorted(required)}")

    itemsets: dict[frozenset[str], dict] = {}
    singleton_support: dict[str, float] = {}
    for row_number, row in enumerate(frame.to_dict(orient="records"), start=2):
        try:
            values = json.loads(row["itemset"])
        except (TypeError, json.JSONDecodeError) as exc:
            raise ValueError(f"Invalid itemset JSON at CSV row {row_number}.") from exc
        if not isinstance(values, list) or not values:
            raise ValueError(f"Itemset at CSV row {row_number} must be a non-empty JSON list.")

        key = frozenset(str(v).strip() for v in values)
        if len(key) != int(row["length"]):
            raise ValueError(f"Itemset length mismatch at CSV row {row_number}.")
        support = float(row["support"])
        count = int(row["support_count"])
        if not 0 <= support <= 1 or count < 0:
            raise ValueError(f"Invalid support values at CSV row {row_number}.")
        itemsets[key] = {"support": support, "support_count": count, "length": len(key)}
        if len(key) == 1:
            singleton_support[next(iter(key))] = support

    return itemsets, singleton_support


def generate_rules(
    itemsets: dict[frozenset[str], dict],
    min_confidence: float,
    min_lift: float,
) -> list[dict]:
    rules: list[dict] = []
    for union, stats in itemsets.items():
        if len(union) < 2:
            continue

        # Enumerate every non-empty proper antecedent; consequent is the complement.
        ordered_items = sorted(union)
        for antecedent_len in range(1, len(ordered_items)):
            for antecedent_tuple in combinations(ordered_items, antecedent_len):
                antecedent = frozenset(antecedent_tuple)
                consequent = union - antecedent
                antecedent_stats = itemsets.get(antecedent)
                consequent_stats = itemsets.get(consequent)
                if antecedent_stats is None or consequent_stats is None:
                    # Downward closure means this indicates an incomplete itemset file.
                    continue

                support = stats["support"]
                confidence = support / antecedent_stats["support"]
                consequent_support = consequent_stats["support"]
                lift = confidence / consequent_support if consequent_support > 0 else float("inf")

                if confidence < min_confidence or lift < min_lift:
                    continue

                rules.append({
                    "antecedent": json.dumps(sorted(antecedent), ensure_ascii=False),
                    "consequent": json.dumps(sorted(consequent), ensure_ascii=False),
                    "union_itemset": json.dumps(sorted(union), ensure_ascii=False),
                    "union_length": len(union),
                    "support_count": stats["support_count"],
                    "support": support,
                    "confidence": confidence,
                    "lift": lift,
                    "antecedent_support": antecedent_stats["support"],
                    "consequent_support": consequent_support,
                })

    # A stable sort prioritizes lift, then confidence, then support.
    rules.sort(key=lambda row: (-row["lift"], -row["confidence"], -row["support"], row["antecedent"], row["consequent"]))
    return rules


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate association rules from Apriori itemsets.")
    parser.add_argument("--input", type=Path, default=DEFAULT_INPUT)
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT_DIR)
    parser.add_argument("--min-confidence", type=float, default=0.30)
    parser.add_argument("--min-lift", type=float, default=1.0)
    args = parser.parse_args()

    if not 0 <= args.min_confidence <= 1:
        parser.error("--min-confidence must be between 0 and 1.")
    if args.min_lift < 0:
        parser.error("--min-lift must be non-negative.")

    input_path = args.input.expanduser().resolve()
    output_dir = args.output_dir.expanduser().resolve()
    output_dir.mkdir(parents=True, exist_ok=True)

    itemsets, _ = load_itemsets(input_path)
    rules = generate_rules(itemsets, args.min_confidence, args.min_lift)

    output_csv = output_dir / "association_rules.csv"
    output_json = output_dir / "association_rules_summary.json"
    columns = [
        "antecedent", "consequent", "union_itemset", "union_length",
        "support_count", "support", "confidence", "lift",
        "antecedent_support", "consequent_support"
    ]
    pd.DataFrame(rules, columns=columns).to_csv(output_csv, index=False, encoding="utf-8")

    summary = {
        "algorithm": "Association rule generation",
        "source_algorithm": "Apriori frequent itemsets",
        "input_file": str(input_path),
        "minimum_confidence": args.min_confidence,
        "minimum_lift": args.min_lift,
        "frequent_itemsets_loaded": len(itemsets),
        "rules_output": len(rules),
        "top_rules_by_lift": rules[:10],
        "completed_utc": datetime.now(timezone.utc).isoformat(),
        "metric_definitions": {
            "support": "Fraction of all transactions containing antecedent and consequent together.",
            "confidence": "Support(antecedent union consequent) divided by support(antecedent).",
            "lift": "Confidence divided by support(consequent); lift > 1 indicates positive association."
        },
        "caveat": "Association rules indicate co-occurrence, not causation. Rules are limited by the maximum itemset length mined by Apriori."
    }
    output_json.write_text(json.dumps(summary, indent=2, ensure_ascii=False), encoding="utf-8")

    print("LAYER 4D — ASSOCIATION RULES: PASSED")
    print(f"Frequent itemsets loaded: {len(itemsets):,}")
    print(f"Minimum confidence: {args.min_confidence:.2%}")
    print(f"Minimum lift: {args.min_lift:.3f}")
    print(f"Rules generated: {len(rules):,}")
    if rules:
        print("\nTop rules by lift:")
        for rule in rules[:5]:
            print(
                f"  {rule['antecedent']} -> {rule['consequent']} | "
                f"support={rule['support']:.4f}, confidence={rule['confidence']:.4f}, "
                f"lift={rule['lift']:.4f}"
            )
    print(f"Rules: {output_csv}")
    print(f"Summary: {output_json}")


if __name__ == "__main__":
    main()
